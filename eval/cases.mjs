const bundle = (...texts) => ({
  evidence: texts.map((text, index) => ({ id: `E${String(index + 1).padStart(3, "0")}`, text })),
});

function evidenceCase(id, split, expected, ...texts) {
  return { id, split, lane: "evidence", bundle: bundle(...texts), expected };
}

function recoveryCase(id, split, category, field, ...texts) {
  return {
    id,
    split,
    lane: "recovery",
    bundle: bundle(...texts),
    expected: { category, field, evidenceRefs: ["E001", "E002"] },
  };
}

